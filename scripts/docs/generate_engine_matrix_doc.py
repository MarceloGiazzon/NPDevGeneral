#!/usr/bin/env python
"""ENGM-2: renders docs/reference/ENGINE_MATRIX.md from scripts/policy/engine-capability-matrix.json.

The matrix JSON is the truth (ENGM-1); this keeps the human page from drifting away from it. Never
edit the markdown by hand -- edit the JSON, then run this script.

Scripts may not read markdown, so drift is detected without reading the page: this script records the
SHA-256 of the render in scripts/policy/engine-matrix-doc-stamp.json, and
scripts/quality/check-engine-matrix.py re-renders in memory and compares it to that stamp. A change to
the matrix (or to this renderer) without a regeneration fails the aiKnowledge gate.

Usage: python scripts/docs/generate_engine_matrix_doc.py
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

WORKSPACE_ROOT = Path(__file__).resolve().parents[2]
MATRIX_PATH = WORKSPACE_ROOT / "scripts" / "policy" / "engine-capability-matrix.json"
DOC_PATH = WORKSPACE_ROOT / "docs" / "reference" / "ENGINE_MATRIX.md"
STAMP_PATH = WORKSPACE_ROOT / "scripts" / "policy" / "engine-matrix-doc-stamp.json"

ENGINE_LABELS = {"h2": "H2", "postgres": "PostgreSQL", "mysql": "MySQL", "sqlserver": "SQL Server"}
CLAIM_MARKS = {"supported": "supported", "partial": "partial", "unsupported": "not proven"}


def _label(capability: str) -> str:
    return capability.replace("_", " ")


def _witness(job: str | None) -> str:
    if not job:
        return "none"
    workflow, _, job_id = job.partition("#")
    return f"[`{job}`](../../.github/workflows/{workflow}) (job `{job_id}`)"


def render(matrix: dict) -> str:
    capabilities = matrix["capabilities"]
    engines = matrix["engines"]
    lines = [
        "# Storage engine support matrix",
        "",
        "<!-- GENERATED by scripts/docs/generate_engine_matrix_doc.py from scripts/policy/engine-capability-matrix.json. "
        "Do not edit by hand. -->",
        "",
        "Which storage engine supports which capability, and **which CI job proves it**. A cell is a claim, "
        "never an assumption: `supported` and `partial` name a real job under `.github/workflows/`, and "
        "`scripts/quality/check-engine-matrix.py` fails when a claim points at a job that does not exist.",
        "",
        "- **supported**: a CI job exercises the capability on that engine.",
        "- **partial**: a job exercises part of it; the note under the engine says what is and is not covered.",
        "- **not proven**: no CI job proves it. This does *not* mean the code path is missing; the note says which.",
        "",
        "A green local run on H2 or in compatibility mode is not a witness for MySQL or SQL Server.",
        "",
        "## At a glance",
        "",
        "| Capability | " + " | ".join(ENGINE_LABELS.get(e, e) for e in engines) + " |",
        "|---|" + "---|" * len(engines),
    ]
    for capability in capabilities:
        cells = [CLAIM_MARKS[engines[e][capability]["claim"]] for e in engines]
        lines.append(f"| {_label(capability)} | " + " | ".join(cells) + " |")
    for engine, row in engines.items():
        lines += ["", f"## {ENGINE_LABELS.get(engine, engine)}", ""]
        for capability in capabilities:
            cell = row[capability]
            lines.append(f"### {_label(capability)}: {CLAIM_MARKS[cell['claim']]}")
            lines.append("")
            lines.append(f"- Witness: {_witness(cell.get('witnessJob'))}")
            lines.append(f"- {cell['note']}")
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_sha256(matrix: dict) -> str:
    return hashlib.sha256(render(matrix).encode("utf-8")).hexdigest()


def main() -> int:
    matrix = json.loads(MATRIX_PATH.read_text(encoding="utf-8"))
    DOC_PATH.write_bytes(render(matrix).encode("utf-8"))
    STAMP_PATH.write_bytes(
        (json.dumps({"renderSha256": render_sha256(matrix)}, indent=2) + "\n").encode("utf-8")
    )
    print(f"wrote {DOC_PATH.relative_to(WORKSPACE_ROOT)} and {STAMP_PATH.relative_to(WORKSPACE_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
