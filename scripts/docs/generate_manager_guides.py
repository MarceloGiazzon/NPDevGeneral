#!/usr/bin/env python3
"""Renders the first-user guides in docs/guides/ (English and Portuguese) from one source.

WHY THIS EXISTS
---------------
The owner wanted a short manual and a "first app in 10 minutes" guide for the first users, people
with a low technical profile (2026-11-03). A hand-written manual starts disagreeing with the
interface the day a screen is renamed -- docs/MANAGER.md still described "seventeen tabs" after the
Manager had eighteen. So the guides here are assembled from the files the Manager ITSELF reads:

  NPDevManager/ui/navigation.json    places, screens, their labels and summaries, per language
  NPDevManager/ui/help-glossary.json what each prerequisite/tool/word is, why, what if missing
  docs/content/manager-guides.yml    the prose, which names places/screens/terms by id

A place, screen or term the prose names that does not exist fails this script (exit 1), so a guide
cannot point at a label the Manager no longer shows.

Like the other docs/content generators, this one only WRITES. Staleness is detected by the caller
with git (run-ai-knowledge-gate.ps1): regenerate, then `git diff --exit-code -- docs/guides/`.
It reads no markdown (check-no-markdown-reads.py).

USAGE
-----
    python scripts/docs/generate_manager_guides.py
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
NAV = REPO / "NPDevManager" / "ui" / "navigation.json"
GLOSSARY = REPO / "NPDevManager" / "ui" / "help-glossary.json"
SOURCE = REPO / "docs" / "content" / "manager-guides.yml"

TOKEN = re.compile(r"\{(place|screen|term|guide|doc):([A-Za-z0-9_./-]+)\}")

HEADINGS = {
    "place": {"en": "Place", "pt": "Lugar"},
    "for": {"en": "What it is for", "pt": "Para que serve"},
    "screens": {"en": "Screens inside", "pt": "Telas dentro dele"},
    "term": {"en": "What", "pt": "O quê"},
    "short": {"en": "What it is", "pt": "O que é"},
    "why": {"en": "Why it matters", "pt": "Por que importa"},
    "missing": {"en": "If it is missing or fails", "pt": "Se faltar ou falhar"},
    "generated": {
        "en": "Generated by `scripts/docs/generate_manager_guides.py` from `docs/content/manager-guides.yml`, "
              "`NPDevManager/ui/navigation.json` and `NPDevManager/ui/help-glossary.json`. Edit those, not this file.",
        "pt": "Gerado por `scripts/docs/generate_manager_guides.py` a partir de `docs/content/manager-guides.yml`, "
              "`NPDevManager/ui/navigation.json` e `NPDevManager/ui/help-glossary.json`. Edite esses, não este arquivo.",
    },
}
LANGUAGE_NAMES = {"en": "English", "pt": "Português"}


class GuideError(Exception):
    pass


def pick(value, lang: str, where: str) -> str:
    if isinstance(value, str):
        return value
    if not isinstance(value, dict) or "en" not in value:
        raise GuideError(f"{where}: expected a {{en: ..., pt: ...}} object with English")
    return value.get(lang, value["en"])


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


class Renderer:
    def __init__(self, nav: dict, glossary: dict, source: dict):
        self.nav = nav
        self.places = {p["id"]: p for p in nav["places"]}
        self.glossary = glossary
        self.terms = {e["id"]: e for e in glossary["entries"]}
        self.guides = source["guides"]

    def rel_link(self, target: str, from_file: str) -> str:
        return Path(os.path.relpath(REPO / target, (REPO / from_file).parent)).as_posix()

    def expand(self, text: str, lang: str, out_file: str, where: str) -> str:
        def sub(m: re.Match) -> str:
            kind, ref = m.group(1), m.group(2)
            if kind == "place":
                place = self.places.get(ref)
                if not place:
                    raise GuideError(f"{where}: unknown place '{ref}'")
                return f"**{pick(place['label'], lang, ref)}**"
            if kind == "screen":
                place_id, _, screen_id = ref.partition("/")
                place = self.places.get(place_id)
                screen = next((s for s in (place or {}).get("screens", []) if s["screen"] == screen_id), None)
                if not screen:
                    raise GuideError(f"{where}: place '{place_id}' has no screen '{screen_id}'")
                return f"**{pick(place['label'], lang, ref)} › {pick(screen['label'], lang, ref)}**"
            if kind == "term":
                entry = self.terms.get(ref)
                if not entry:
                    raise GuideError(f"{where}: unknown glossary term '{ref}'")
                return pick(entry["term"], lang, ref)
            if kind == "guide":
                guide = self.guides.get(ref)
                if not guide:
                    raise GuideError(f"{where}: unknown guide '{ref}'")
                return f"[{pick(guide['title'], lang, ref)}]({self.rel_link(guide['out'][lang], out_file)})"
            if kind == "doc":
                if not (REPO / "docs" / ref).exists():
                    raise GuideError(f"{where}: docs/{ref} does not exist")
                return f"[{ref}]({self.rel_link('docs/' + ref, out_file)})"
            raise GuideError(f"{where}: unknown token kind '{kind}'")

        return TOKEN.sub(sub, text)

    def places_table(self, lang: str) -> list[str]:
        h = HEADINGS
        rows = [f"| {h['place'][lang]} | {h['for'][lang]} | {h['screens'][lang]} |", "|---|---|---|"]
        groups = self.nav.get("groups", {})
        for place in self.nav["places"]:
            names = []
            for s in place["screens"]:
                label = pick(s["label"], lang, place["id"])
                if s.get("group"):
                    label += f" ({pick(groups[s['group']], lang, s['group']).lower()})"
                names.append(label)
            rows.append(
                f"| {place.get('icon', '')} **{cell(pick(place['label'], lang, place['id']))}** "
                f"| {cell(pick(place['summary'], lang, place['id']))} | {cell(', '.join(names))} |"
            )
        return rows

    def glossary_tables(self, lang: str, kinds: list[str], with_kind_headings: bool, out_file: str) -> list[str]:
        h = HEADINGS
        lines: list[str] = []
        for kind in kinds:
            entries = [e for e in self.glossary["entries"] if e["kind"] == kind]
            if not entries:
                raise GuideError(f"glossary has no entries of kind '{kind}'")
            if with_kind_headings:
                lines += [f"**{pick(self.glossary['kinds'][kind], lang, kind)}**", ""]
            lines += [f"| {h['term'][lang]} | {h['short'][lang]} | {h['why'][lang]} | {h['missing'][lang]} |",
                      "|---|---|---|---|"]
            for e in entries:
                text = e.get(lang, e["en"])
                where = f"glossary {e['id']}"
                short, why, missing = (self.expand(text[k], lang, out_file, where) for k in ("short", "why", "ifMissing"))
                lines.append(
                    f"| **{cell(pick(e['term'], lang, e['id']))}** | {cell(short)} | {cell(why)} | {cell(missing)} |"
                )
            lines.append("")
        return lines

    def render(self, guide_id: str, lang: str) -> tuple[str, str]:
        guide = self.guides[guide_id]
        out_file = guide["out"][lang]
        others = [
            f"[{LANGUAGE_NAMES[other]}]({self.rel_link(guide['out'][other], out_file)})"
            for other in guide["out"] if other != lang
        ]
        lines = [
            f"<!-- {HEADINGS['generated'][lang]} -->",
            "",
            f"# {pick(guide['title'], lang, guide_id)}",
            "",
            f"*{' · '.join(others)}*",
            "",
        ]
        for i, section in enumerate(guide["sections"]):
            where = f"{guide_id}.sections[{i}]"
            if "heading" in section:
                lines += [f"## {self.expand(pick(section['heading'], lang, where), lang, out_file, where)}", ""]
            if "body" in section:
                lines += [self.expand(pick(section["body"], lang, where), lang, out_file, where).rstrip(), ""]
            generated = section.get("generated")
            if generated == "places":
                lines += self.places_table(lang) + [""]
            elif generated == "glossary":
                kinds = section.get("kinds") or []
                lines += self.glossary_tables(lang, kinds, with_kind_headings=len(kinds) > 1, out_file=out_file)
            elif generated is not None:
                raise GuideError(f"{where}: unknown generated section '{generated}'")
        text = "\n".join(lines).rstrip() + "\n"
        return out_file, re.sub(r"\n{3,}", "\n\n", text)


def main() -> int:
    nav = json.loads(NAV.read_text(encoding="utf-8"))
    glossary = json.loads(GLOSSARY.read_text(encoding="utf-8"))
    source = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    renderer = Renderer(nav, glossary, source)
    try:
        outputs = [renderer.render(g, lang) for g in source["guides"] for lang in source["languages"]]
    except GuideError as e:
        print(f"FAIL  {e}", file=sys.stderr)
        return 1
    for out_file, text in outputs:
        path = REPO / out_file
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {out_file}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
