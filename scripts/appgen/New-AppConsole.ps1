<script>
const TOKEN='__TOKEN__'; const ACTIONS=__ACTIONS__; const FREEFORM=__FREEFORM__;
const term=document.getElementById('term'); const statusEl=document.getElementById('status');
let es=null;
function line(t){ const atBottom = term.scrollTop+term.clientHeight >= term.scrollHeight-4; term.textContent += t+'\n'; if(atBottom) term.scrollTop=term.scrollHeight; }
function clearTerm(){ term.textContent=''; }
function setBusy(b){ document.querySelectorAll('#btns button,.ff button').forEach(x=>x.disabled=b); statusEl.textContent=b?'running...':'idle'; }
function stream(url,label){
  if(es){es.close();}
  setBusy(true); line('\n$ '+label);
  es=new EventSource(url);
  es.onmessage=e=>line(e.data);
  es.addEventListener('done',e=>{ line('[exit '+e.data+']'); es.close(); es=null; setBusy(false); });
  es.onerror=()=>{ if(es){es.close();es=null;} setBusy(false); statusEl.textContent='disconnected'; };
}
function run(id,label){ stream('/run?action='+encodeURIComponent(id)+'&token='+TOKEN, label); }
function runFree(){ const v=document.getElementById('ff').value.trim(); if(!v)return; stream('/run?action=exec&cmd='+encodeURIComponent(v)+'&token='+TOKEN, v); }
const btns=document.getElementById('btns');
ACTIONS.forEach(a=>{ const b=document.createElement('button'); b.textContent=a.label; b.onclick=()=>run(a.id,a.label); btns.appendChild(b); });
if(FREEFORM){ document.getElementById('ffbox').style.display='flex'; }
line('Ready. Whitelisted actions: '+ACTIONS.map(a=>a.label).join(', ')+(FREEFORM?'  + free-form':''));
