poll(); setInterval(poll, 3000);
</script></body></html>
'@

$serve = $serve.Replace('@@APPID@@', $AppId).Replace('@@OPSDIR@@', $OpsDir).Replace('@@OUTROOT@@', $OutRoot).Replace('@@MODE@@', $Mode).Replace('@@CONSOLEPORT@@', "$ConsolePort")
Set-Content -LiteralPath (Join-Path $OpsDir 'Serve-AppConsole.ps1') -Value $serve -Encoding UTF8
